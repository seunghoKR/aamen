export type AuthTranslationKey = keyof (typeof authTranslations)['ko']
export type AuthLocale = keyof typeof authTranslations

export function getAuthText(locale: string, key: AuthTranslationKey, fallback = ''): string {
  const loc = (locale in authTranslations ? locale : 'ko') as AuthLocale
  const item = authTranslations[loc]
  if (item && key in item) {
    return (item as Record<string, string>)[key]
  }
  const koItem = authTranslations['ko']
  if (koItem && key in koItem) {
    return (koItem as Record<string, string>)[key]
  }
  return fallback
}
